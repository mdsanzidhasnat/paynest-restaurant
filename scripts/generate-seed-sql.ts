import fs from 'node:fs';
import bcrypt from 'bcrypt';
import {
  INITIAL_CATEGORIES,
  INITIAL_COMPLETED_ORDERS,
  INITIAL_FLOORS,
  INITIAL_INGREDIENTS,
  INITIAL_MENU_ITEMS,
  INITIAL_TABLES,
  RESTAURANT_SETTINGS,
  variantPrice,
  dayLabel,
  isoDaysAgo,
} from '../src/data/seedData.ts';
import { getDemoAccounts } from '../server/seed.ts';
import { calculateOrderTotals } from '../server/billing.ts';
import { PROJECT_ROOT } from '../server/paths.ts';

/**
 * Regenerates docs/seed.sql from the same constants the runtime seed uses.
 * The password below is a documented placeholder; only bcrypt hashes are
 * ever written to the SQL file. Never use it for a real deployment.
 */
const DEMO_SQL_PASSWORD = 'ChangeMe-Demo-123';

for (const key of ['ADMIN', 'MANAGER', 'WAITER', 'KITCHEN', 'CASHIER'] as const) {
  process.env[`${key}_PASSWORD`] = DEMO_SQL_PASSWORD;
}
process.env.SEED_DEMO_DATA = 'true';

type SqlValue = string | number | null;

function quote(value: SqlValue): string {
  if (value === null) return 'NULL';
  if (typeof value === 'number') return String(value);
  return `'${value.replaceAll("'", "''")}'`;
}

function insert(table: string, columns: readonly string[], rows: SqlValue[][]): string {
  if (rows.length === 0) return '';
  const values = rows.map((row) => `  (${row.map(quote).join(', ')})`).join(',\n');
  return `INSERT INTO ${table} (${columns.join(', ')}) VALUES\n${values};\n`;
}

const accounts = getDemoAccounts();
const lines: string[] = [
  '-- Restaurant demo data. Generated by npm run seed:sql; do not edit by hand.',
  '-- Passwords are bcrypt hashes of a documented placeholder, never plaintext.',
  '-- Dates are stored as ISO timestamps computed relative to generation time.',
  '',
  'BEGIN IMMEDIATE;',
  '',
];

lines.push(
  insert(
    'users',
    ['id', 'name', 'email', 'phone', 'role', 'active', 'avatar', 'last_active', 'password_hash', 'created_at'],
    accounts.map((account) => [
      account.id,
      account.name,
      account.email,
      '+880 1700-000000',
      account.role,
      1,
      account.avatar,
      account.lastActive,
      bcrypt.hashSync(account.password, 10),
      isoDaysAgo(10),
    ])
  )
);

lines.push(
  insert(
    'settings',
    ['id', 'restaurant_name', 'phone', 'email', 'address', 'currency_symbol', 'vat_percent', 'service_charge_percent', 'invoice_prefix', 'paper_size', 'receipt_footer', 'low_stock_default', 'auto_confirm_public_orders'],
    [[
      1,
      RESTAURANT_SETTINGS.restaurantName,
      RESTAURANT_SETTINGS.phone,
      RESTAURANT_SETTINGS.email,
      RESTAURANT_SETTINGS.address,
      RESTAURANT_SETTINGS.currencySymbol,
      RESTAURANT_SETTINGS.vatPercent,
      RESTAURANT_SETTINGS.serviceChargePercent,
      RESTAURANT_SETTINGS.invoicePrefix,
      RESTAURANT_SETTINGS.paperSize,
      RESTAURANT_SETTINGS.receiptFooter,
      RESTAURANT_SETTINGS.lowStockDefault,
      0,
    ]]
  )
);

lines.push(
  insert('floors', ['id', 'name', 'sort_order'], INITIAL_FLOORS.map((floor) => [floor.id, floor.name, floor.sortOrder]))
);

lines.push(
  insert(
    'tables',
    ['id', 'floor_id', 'number', 'seats', 'x', 'y', 'shape', 'status', 'qr_secret_version'],
    INITIAL_TABLES.map((table) => [table.id, table.floorId, table.number, table.seats, table.x, table.y, table.shape, 'free', 1])
  )
);

lines.push(
  insert(
    'menu_categories',
    ['id', 'name', 'description', 'color', 'sort_order'],
    INITIAL_CATEGORIES.map((category) => [category.id, category.name, category.description, category.color, category.sortOrder])
  )
);

lines.push(
  insert(
    'ingredients',
    ['id', 'name', 'unit', 'stock', 'low_stock_threshold', 'unit_cost'],
    INITIAL_INGREDIENTS.map((ingredient) => [
      ingredient.id, ingredient.name, ingredient.unit, ingredient.stock, ingredient.lowStockThreshold, ingredient.unitCost,
    ])
  )
);

lines.push(
  insert(
    'menu_items',
    ['id', 'category_id', 'name', 'description', 'image', 'price', 'prep_station', 'sort_order'],
    INITIAL_MENU_ITEMS.map((item) => [
      item.id, item.categoryId, item.name, item.description, item.image, item.price, item.prepStation, item.sortOrder,
    ])
  )
);

lines.push(
  insert(
    'item_variants',
    ['id', 'menu_item_id', 'name', 'price', 'sort_order'],
    INITIAL_MENU_ITEMS.flatMap((item) =>
      item.variants.map((variant, index) => [
        `${item.id}v${index + 1}`,
        item.id,
        variant.name,
        variantPrice(item, variant),
        index,
      ] as SqlValue[])
    )
  )
);

lines.push(
  insert(
    'recipe_items',
    ['menu_item_id', 'ingredient_id', 'quantity'],
    INITIAL_MENU_ITEMS.flatMap((item) =>
      Object.entries(item.recipe)
        .filter(([, quantity]) => quantity > 0)
        .map(([ingredientId, quantity]) => [item.id, ingredientId, quantity] as SqlValue[])
    )
  )
);

const orderRows: SqlValue[][] = [];
const orderItemRows: SqlValue[][] = [];
const paymentRows: SqlValue[][] = [];

INITIAL_COMPLETED_ORDERS.forEach((sample, index) => {
  const createdAt = isoDaysAgo(sample.daysAgo, sample.minutesAgo);
  const closedAt = isoDaysAgo(sample.daysAgo, sample.minutesAgo - 45);
  const examinedLines = sample.lines.map((line, lineIndex) => {
    const item = INITIAL_MENU_ITEMS.find((entry) => entry.id === line.itemId);
    if (!item) throw new Error(`Seed order references unknown item ${line.itemId}`);
    const variant = item.variants[line.variantIndex] ?? item.variants[0];
    return { item, variant, lineIndex, quantity: line.quantity };
  });
  const totals = calculateOrderTotals(
    examinedLines.map((line) => ({ quantity: line.quantity, unitPrice: variantPrice(line.item, line.variant) })),
    sample.discount,
    {
      vatPercent: RESTAURANT_SETTINGS.vatPercent,
      serviceChargePercent: RESTAURANT_SETTINGS.serviceChargePercent,
    }
  );
  const orderId = `o${index + 1}`;
  orderRows.push([
    orderId, `ORD-${String(index + 1).padStart(4, '0')}`, `INV-${String(index + 1).padStart(4, '0')}`,
    sample.tableId, 'waiter', 'closed', sample.openedById, sample.guestCount,
    totals.subtotal, totals.discount, totals.vatAmount, totals.serviceCharge, totals.total,
    'paid', sample.method, createdAt, createdAt, closedAt, closedAt,
  ]);
  for (const line of examinedLines) {
    orderItemRows.push([
      `oi${index + 1}_${line.lineIndex + 1}`, orderId, line.item.id,
      `${line.item.id}v${line.item.variants.indexOf(line.variant) + 1}`,
      line.item.name, line.variant.name, line.quantity, 'served',
      variantPrice(line.item, line.variant), variantPrice(line.item, line.variant) * line.quantity, createdAt, closedAt,
    ]);
  }
  paymentRows.push([`pay${index + 1}`, orderId, sample.method, totals.total, 'u5', closedAt]);
});

lines.push(
  insert(
    'orders',
    ['id', 'order_number', 'bill_number', 'table_id', 'source', 'status', 'opened_by', 'guest_count', 'subtotal', 'discount', 'vat_amount', 'service_charge', 'total', 'payment_status', 'payment_method', 'created_at', 'opened_at', 'closed_at', 'paid_at'],
    orderRows
  )
);
lines.push(
  insert(
    'order_items',
    ['id', 'order_id', 'menu_item_id', 'variant_id', 'name_snapshot', 'variant_name_snapshot', 'quantity', 'status', 'unit_price', 'line_total', 'created_at', 'served_at'],
    orderItemRows
  )
);
lines.push(
  insert('payments', ['id', 'order_id', 'method', 'amount', 'recorded_by', 'created_at'], paymentRows)
);

const dailyRows: SqlValue[][] = [];
for (let daysAgo = 6; daysAgo >= 0; daysAgo -= 1) {
  const label = dayLabel(daysAgo);
  const matching = INITIAL_COMPLETED_ORDERS.filter((order) => order.daysAgo === daysAgo);
  const sales = matching.reduce((sum, order) => {
    const billable = order.lines.map((line) => {
      const item = INITIAL_MENU_ITEMS.find((entry) => entry.id === line.itemId);
      const variant = item?.variants[line.variantIndex] ?? item?.variants[0];
      return { quantity: line.quantity, unitPrice: item && variant ? variantPrice(item, variant) : 0 };
    });
    return sum + calculateOrderTotals(billable, order.discount, {
      vatPercent: RESTAURANT_SETTINGS.vatPercent,
      serviceChargePercent: RESTAURANT_SETTINGS.serviceChargePercent,
    }).total;
  }, 0);
  dailyRows.push([label.date, label.day, label.dateLabel, sales, matching.length, 0, 0, 0]);
}
lines.push(
  insert(
    'daily_sales',
    ['sales_date', 'day', 'date_label', 'sales', 'orders', 'vat', 'service_charge', 'profit'],
    dailyRows
  )
);

lines.push(
  insert('number_sequences', ['name', 'last_value'], [['order', orderRows.length], ['bill', orderRows.length]])
);
lines.push(`INSERT OR IGNORE INTO schema_version (version, description) VALUES
  (1, 'initial restaurant schema and number sequences'),
  (2, 'bill splits, item status events, table transfers and cancel reason'),
  (3, 'one stock movement per ingredient per served item'),
  (4, 'public QR orders: pending confirmation and auto-confirm setting');`);
lines.push('COMMIT;', '');

const outputPath = new URL('../docs/seed.sql', import.meta.url);
fs.writeFileSync(outputPath, lines.join('\n'));
console.log(`Wrote ${new URL('../docs/seed.sql', import.meta.url).pathname} (${PROJECT_ROOT})`);
